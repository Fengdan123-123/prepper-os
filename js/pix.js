/* 生成像素图标 SVG */
function pix(name, size, color){
  const rows = SPRITE[name] || SPRITE.grid;
  const s = size || 16;
  let rects = '';
  rows.forEach((row, y) => {
    for(let x=0; x<8; x++){
      if(row[x] === '#') rects += `<rect x="${x}" y="${y}" width="1" height="1"/>`;
    }
  });
  return `<svg viewBox="0 0 8 8" width="${s}" height="${s}" shape-rendering="crispEdges"
    style="image-rendering:pixelated;vertical-align:-2px;fill:${color||'currentColor'}">${rects}</svg>`;
}

